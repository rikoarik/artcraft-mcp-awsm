import assert from 'node:assert/strict';
import {designBrief,confirmedBrief} from '../build/tools/design-brief.js';
import {designQuickstart} from '../build/tools/design-quickstart.js';
import {McpGateway} from '../build/tools/mcp-gateway.js';
const initial=designBrief({mode:"guided"});
assert.equal(initial.status,'needs-answers');
assert.equal(initial.questions[0].field,'outcome');
assert.equal(initial.answers.threeD,undefined);
assert.throws(()=>designBrief({briefId:initial.briefId,confirm:true}),/incomplete/);
assert.throws(()=>confirmedBrief(initial.briefId),/approve/);
assert.throws(()=>designBrief({briefId:'unknown'}),/expired/);
const website={outcome:'website',category:'marketing',threeD:'none',projectMode:'new',target:'/tmp/my-site',style:'User reference',scope:'Home and contact'};
assert.throws(()=>designBrief({mode:"guided",answers:website,confirm:true}),/summary first/);
const summary=designBrief({briefId:initial.briefId,answers:website});
assert.equal(summary.status,'needs-confirmation');
assert.deepEqual(summary.summary,website);
const ready=designBrief({briefId:summary.briefId,confirm:true});
assert.equal(ready.status,'ready');
assert.deepEqual(ready.route.crafts,[]);
const gateway=new McpGateway();
await assert.rejects(gateway.prepare({craft:'solidcraft',task:'create',briefId:ready.briefId}),/not part/);
await assert.rejects(gateway.prepare({craft:'figcraft',task:'edit'}),/Brief missing/);
const fast=await designQuickstart({briefId:ready.briefId,brief:'admin mobile dashboard keywords must not change the selected category'});
assert.equal(fast.kind,'marketing');
assert.equal(fast.choices.style,'User reference');
await assert.rejects(designQuickstart({briefId:ready.briefId,brief:'Make a dashboard',kind:'admin'}),/conflicts/);
await assert.rejects(designQuickstart({briefId:ready.briefId,brief:'Make a website',root:'/other'}),/target/);
const edited=designBrief({briefId:ready.briefId,answers:{threeD:'interactive'}});
assert.equal(edited.status,'needs-answers');
assert(edited.questions.some(q=>q.field==='session'));
assert(edited.questions.some(q=>q.field==='preview'));
assert.throws(()=>confirmedBrief(ready.briefId),/approve/);
const withSession=designBrief({briefId:ready.briefId,answers:{session:'visible',preview:'none'}});
assert.equal(withSession.status,'needs-confirmation');
assert.deepEqual(designBrief({briefId:ready.briefId,confirm:true}).route.crafts,['solidcraft']);
const no3d=designBrief({briefId:ready.briefId,answers:{threeD:'none'}});
assert.equal(no3d.summary.preview,undefined);
assert.deepEqual(designBrief({briefId:ready.briefId,confirm:true}).route.crafts,[]);
const changed=designBrief({briefId:ready.briefId,answers:{outcome:'cad'}});
assert.equal(changed.status,'needs-answers');
assert.equal(changed.answers.style,undefined);
const fig=designBrief({mode:"guided",answers:{...website,outcome:'figcraft',threeD:'none',session:'visible'}});
assert.deepEqual(designBrief({briefId:fig.briefId,confirm:true}).route.crafts,['figcraft']);
await assert.rejects(designQuickstart({briefId:fig.briefId,brief:'Make a website'}),/not selected/);
const model=designBrief({mode:"guided",answers:{outcome:'model-3d',source:'direct',projectMode:'new',target:'New model',style:'Brushed metal',scope:'A speaker',session:'visible'}});
assert.deepEqual(designBrief({briefId:model.briefId,confirm:true}).route.crafts,['solidcraft']);
await assert.rejects(gateway.call({server:'solidcraft',tool:'execute',arguments:{command:'create'}}),/Brief missing/);
await assert.rejects(gateway.call({server:'cadcraft',tool:'batch',briefId:fig.briefId}),/not part/);
const cadSource=designBrief({briefId:model.briefId,answers:{source:'cadcraft'}});
assert.deepEqual(designBrief({briefId:cadSource.briefId,confirm:true}).route.crafts,['cadcraft','solidcraft']);
const auto=designBrief({answers:{outcome:'website',projectMode:'new',target:'/tmp/prompt-first'}});
assert.equal(auto.status,'needs-recommendations');
assert(auto.fields.includes('style'));
const recommended=designBrief({briefId:auto.briefId,recommendations:{category:'admin',style:'Operational editorial',threeD:'none',scope:'Queue, detail, edit',motion:'feedback'}});
assert.equal(recommended.status,'ready');
assert.equal(confirmedBrief(auto.briefId).category,'admin');
assert.throws(()=>designBrief({briefId:auto.briefId,recommendations:{target:'/other'}}),/cannot choose/);
assert.throws(()=>designBrief({briefId:auto.briefId,recommendations:{style:'Override'}}),/conflicts/);
console.log('Guided and automatic brief tests passed');
